// The monthly placement refresh for the Worker (round 43 step 3): rules_data/placement/*.csv -> ONE SQL file that
// replaces the six placement_* tables' contents, for
//
//   npx wrangler d1 execute cfig-eligibility --remote --file=cloudflare/build/placement_sync.sql
//
// usage (cwd = the repo root):  node cloudflare/scripts/sync_placement.mjs [--csv-dir DIR] [--out FILE]
//
// The CSVs stay the source (rules_data/placement/sync_from_out.py still writes them, and they stay committed);
// this file is what D1 gets. Same CSVs -> byte-identical SQL (no timestamps in it), so a re-run is harmless.
//
// All or nothing: wrangler runs a --remote --file as one D1 import ("if the execution fails to complete, your DB
// will return to its original state and you can safely retry" -- wrangler 4.149's own message; D1 is also
// unavailable to queries while it runs, so no panel ever reads a half-written table), and --local runs the file as
// one batch(), i.e. one transaction. The file therefore holds no BEGIN/COMMIT (D1 refuses them). After a refresh,
// `cloudflare/scripts/check_placement.sql` compares each table's row count with the counts this file wrote into
// placement_meta (sync_rows_*).
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { inserts, readCsv } from "./lib.mjs";
import { countyKey, monthIndex } from "../src/placement.js";

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, "..", "..");
const FILES = ["placement_zip.csv", "placement_county.csv", "placement_profile.csv", "placement_markets.csv",
  "placement_meta.csv"];
const MONTH = /^\d{4}-(0[1-9]|1[0-2])$/;

function arg(name, dflt) {
  const i = process.argv.indexOf(name);
  return i > 0 ? process.argv[i + 1] : dflt;
}

export function buildSyncSql(csvDir) {
  const problems = [];
  const read = (f) => readCsv(join(csvDir, f));
  const check = (file, r, i, cols) => {
    for (const c of cols) if (!(c in r)) problems.push(`${file}: no column ${c}`);
    if ("month" in r && !MONTH.test(r.month)) problems.push(`${file} line ${i + 2}: month ${JSON.stringify(r.month)}`);
    if ("n" in r && !/^\d+$/.test(r.n)) problems.push(`${file} line ${i + 2}: n ${JSON.stringify(r.n)}`);
  };
  const zip = read("placement_zip.csv"), county = read("placement_county.csv"), profile = read("placement_profile.csv");
  const markets = read("placement_markets.csv"), meta = read("placement_meta.csv");
  zip.forEach((r, i) => check("placement_zip.csv", r, i, ["month", "zip", "market", "n"]));
  county.forEach((r, i) => check("placement_county.csv", r, i, ["month", "county", "market", "n"]));
  profile.forEach((r, i) => check("placement_profile.csv", r, i, ["month", "dim", "value", "market", "n"]));
  markets.forEach((r, i) => check("placement_markets.csv", r, i, ["market", "program_prefix"]));
  meta.forEach((r, i) => check("placement_meta.csv", r, i, ["key", "value"]));
  const metaMap = Object.fromEntries(meta.map((r) => [r.key, r.value]));
  if (!metaMap.data_through) problems.push("placement_meta.csv: no data_through");
  if (zip.length === 0 || markets.length === 0) problems.push("placement_zip.csv / placement_markets.csv is empty");
  if (problems.length) throw new Error("not synced:\n  " + problems.slice(0, 20).join("\n  "));

  // placement.py's T["all"]: every ZIP row, here summed per (month, market) in first-appearance order
  const all = new Map();
  for (const r of zip) {
    const k = `${r.month}\u0000${r.market}`;
    if (!all.has(k)) all.set(k, [r.month, r.market, 0]);
    all.get(k)[2] += parseInt(r.n, 10);
  }
  const allRows = [...all.values()].map(([month, market, n], i) => [i + 1, month, monthIndex(month), market, n]);

  const hash = createHash("sha256");
  for (const f of FILES) hash.update(f + "\n").update(readFileSync(join(csvDir, f)));
  const extra = {
    sync_rows_zip: zip.length, sync_rows_county: county.length, sync_rows_profile: profile.length,
    sync_rows_markets: markets.length, sync_rows_all: allRows.length,
    sync_csv_sha256: hash.digest("hex").slice(0, 16),
  };
  const metaRows = [...meta.map((r) => [r.key, r.value]), ...Object.entries(extra).map(([k, v]) => [k, String(v)])];

  const sql = [
    "-- Generated by cloudflare/scripts/sync_placement.mjs from rules_data/placement/*.csv -- do not edit.",
    `-- data_through ${metaMap.data_through}, ${zip.length} ZIP / ${county.length} county / ${profile.length} profile rows, `
      + `csv sha256 ${extra.sync_csv_sha256}.`,
    "-- One D1 import: all of it applies or none of it does (see the script's header).",
    "DELETE FROM placement_zip;", "DELETE FROM placement_county;", "DELETE FROM placement_profile;",
    "DELETE FROM placement_all;", "DELETE FROM placement_markets;", "DELETE FROM placement_meta;",
    ...inserts("placement_zip", ["seq", "month", "mi", "zip", "market", "n"],
      zip.map((r, i) => [i + 1, r.month, monthIndex(r.month), r.zip, r.market, parseInt(r.n, 10)])),
    ...inserts("placement_county", ["seq", "month", "mi", "county", "county_key", "market", "n"],
      county.map((r, i) => [i + 1, r.month, monthIndex(r.month), r.county, countyKey(r.county), r.market, parseInt(r.n, 10)])),
    ...inserts("placement_profile", ["seq", "month", "mi", "dim", "value", "market", "n"],
      profile.map((r, i) => [i + 1, r.month, monthIndex(r.month), r.dim, r.value, r.market, parseInt(r.n, 10)])),
    ...inserts("placement_all", ["seq", "month", "mi", "market", "n"], allRows),
    ...inserts("placement_markets", ["seq", "market", "program_prefix"],
      markets.map((r, i) => [i + 1, r.market, r.program_prefix])),
    ...inserts("placement_meta", ["key", "value"], metaRows),
  ].join("\n") + "\n";
  return { sql, counts: extra, dataThrough: metaMap.data_through };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const csvDir = resolve(arg("--csv-dir", join(ROOT, "rules_data", "placement")));
  const out = resolve(arg("--out", join(ROOT, "cloudflare", "build", "placement_sync.sql")));
  try {
    const { sql, counts, dataThrough } = buildSyncSql(csvDir);
    mkdirSync(dirname(out), { recursive: true });
    writeFileSync(out, sql, "utf8");
    console.log(`wrote ${out} (${Math.round(sql.length / 1024)} KB): data through ${dataThrough}; `
      + Object.entries(counts).map(([k, v]) => `${k.replace("sync_", "")} ${v}`).join(", "));
    console.log("next: npx wrangler d1 execute cfig-eligibility --remote --file=" + out.replaceAll("\\", "/"));
  } catch (e) {
    console.error(e.message);
    process.exit(1);
  }
}
