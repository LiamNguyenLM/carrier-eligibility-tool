// Railway's JSONL logs -> SQL for D1 (round 43 step 3). One-off (or repeated: re-running never duplicates a row).
//
// usage (cwd = the repo root):
//   node cloudflare/scripts/import_logs.mjs [--feedback feedback_log.jsonl] [--usage usage_log.jsonl]
//        [--out cloudflare/build/import_logs.sql]
//   npx wrangler d1 execute cfig-eligibility --remote --file=cloudflare/build/import_logs.sql
//
// Liam downloads the two files from the Railway volume (carrier_docs_db/feedback_log.jsonl and usage_log.jsonl).
// Each line becomes one INSERT OR IGNORE keyed on dedup_key = sha256 of the line's JSON with its keys sorted, so
// a line already imported is skipped (the same file twice, or a later download that still holds the old lines).
// Imported rows get source 'railway', email '' (Railway never knew who sent them) and received_at = their ts.
// A line that is not JSON, or has no ts, is counted and skipped. The file holds real feedback: keep it out of git
// (cloudflare/build/ is git-ignored) and delete it after the import.
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { inserts } from "./lib.mjs";
import { feedbackCsvLine } from "../src/csv.js";

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, "..", "..");

function canonical(v) {
  if (Array.isArray(v)) return "[" + v.map(canonical).join(",") + "]";
  if (v && typeof v === "object") return "{" + Object.keys(v).sort().map((k) => JSON.stringify(k) + ":" + canonical(v[k])).join(",") + "}";
  return JSON.stringify(v);
}
const key = (line) => createHash("sha256").update(canonical(line)).digest("hex");
const s = (v) => (v === undefined || v === null ? "" : typeof v === "string" ? v : JSON.stringify(v));
const n = (v) => (typeof v === "number" && Number.isFinite(v) ? v : 0);
const j = (v, d) => JSON.stringify(v === undefined || v === null ? d : v);

export function readJsonl(path) {
  const lines = [], bad = [];
  readFileSync(path, "utf8").split(/\r?\n/).forEach((raw, i) => {
    if (!raw.trim()) return;
    try {
      const o = JSON.parse(raw);
      if (o && typeof o === "object" && !Array.isArray(o) && typeof o.ts === "string" && o.ts) lines.push(o);
      else bad.push(i + 1);
    } catch {
      bad.push(i + 1);
    }
  });
  return { lines, bad };
}

export const FEEDBACK_COLS = ["dedup_key", "source", "received_at", "email", "ts", "app_version", "name", "property_details",
  "carrier", "display_name", "verdict", "reasons", "deciding_rows", "model", "rules_table", "checked_topics", "choice",
  "comment", "csv_row"];
const feedbackBase = (o) => [key(o), "railway", o.ts, "", o.ts, s(o.app_version), s(o.name),
  j(o.property_details, {}), s(o.carrier), s(o.display_name), s(o.verdict), j(o.reasons, []), j(o.deciding_rows, []),
  s(o.model), o.rules_table ? 1 : 0, o.checked_topics === undefined || o.checked_topics === null ? null : j(o.checked_topics),
  s(o.choice) || "Not sure", s(o.comment)];
export const feedbackRow = (o) => {
  const v = feedbackBase(o);
  return [...v, feedbackCsvLine(Object.fromEntries(FEEDBACK_COLS.slice(0, v.length).map((c, i) => [c, v[i]])))];
};

export const USAGE_COLS = ["dedup_key", "source", "received_at", "email", "ts", "app_version", "model", "effort", "fallback",
  "calls", "cost", "wall_s", "carriers", "retries", "timings"];
export const usageRow = (o) => [key(o), "railway", o.ts, "", o.ts, s(o.app_version), s(o.model), s(o.effort),
  o.fallback ? 1 : 0, j(o.calls, {}), n(o.cost), n(o.wall_s), Math.trunc(n(o.carriers)), Math.trunc(n(o.retries)),
  j(o.timings, {})];

export function buildImportSql({ feedback, usage }) {
  const out = ["-- Generated by cloudflare/scripts/import_logs.mjs. INSERT OR IGNORE on dedup_key: safe to run again."];
  const report = [];
  for (const [label, path, table, cols, row] of [["feedback", feedback, "feedback", FEEDBACK_COLS, feedbackRow],
    ["usage", usage, "usage", USAGE_COLS, usageRow]]) {
    if (!path) continue;
    if (!existsSync(path)) throw new Error(`${label}: no file ${path}`);
    const { lines, bad } = readJsonl(path);
    out.push(...inserts(table, cols, lines.map(row), { per: 100, verb: "INSERT OR IGNORE" }));
    report.push(`${label}: ${lines.length} lines` + (bad.length ? `, ${bad.length} skipped (not JSON or no ts: lines ${bad.slice(0, 10).join(", ")}${bad.length > 10 ? ", ..." : ""})` : ""));
  }
  return { sql: out.join("\n") + "\n", report };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const arg = (name, d) => { const i = process.argv.indexOf(name); return i > 0 ? process.argv[i + 1] : d; };
  const feedback = arg("--feedback"), usage = arg("--usage");
  if (!feedback && !usage) {
    console.error("give --feedback FILE and/or --usage FILE");
    process.exit(2);
  }
  const out = resolve(arg("--out", join(ROOT, "cloudflare", "build", "import_logs.sql")));
  try {
    const { sql, report } = buildImportSql({ feedback: feedback && resolve(feedback), usage: usage && resolve(usage) });
    mkdirSync(dirname(out), { recursive: true });
    writeFileSync(out, sql, "utf8");
    console.log(report.join("\n"));
    console.log(`wrote ${out}\nnext: npx wrangler d1 execute cfig-eligibility --remote --file=${out.replaceAll("\\", "/")}`);
  } catch (e) {
    console.error(e.message);
    process.exit(1);
  }
}
